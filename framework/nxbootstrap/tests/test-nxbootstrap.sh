# Reloading after an older library was sourced must replace its functions. The
# published 0.5.0 assigned its version before the idempotence guard and could
# silently retain the old nxbootstrap_main body.
reload_result=$(bash -c '
  NXBOOTSTRAP_LIBRARY_LOADED=1
  NXBOOTSTRAP_VERSION=0.4.0
  NXBOOTSTRAP_LIBRARY_GENERATION=nxbootstrap-library-v4
  nxbootstrap_main() { printf "stale-main\n"; }
  stale=$(declare -f nxbootstrap_main)
  source "$1"
  current=$(declare -f nxbootstrap_main)
  [[ $NXBOOTSTRAP_VERSION == 0.5.1 ]]
  [[ $NXBOOTSTRAP_LIBRARY_GENERATION == nxbootstrap-library-v501 ]]
  [[ $current != "$stale" ]]
  source "$1"
  [[ $(declare -f nxbootstrap_main) == "$current" ]]
  printf "reload-ok\n"
' _ "$PROJECT_ROOT/nxbootstrap.sh")
[[ $reload_result == reload-ok ]] ||
  fail '0.5.1 did not replace a previously loaded 0.4.x function body'

