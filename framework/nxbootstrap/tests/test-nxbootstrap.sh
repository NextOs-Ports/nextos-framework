  local expected_status=$1
  shift
  set +e
  NXBOOTSTRAP_TEST_RESULT=$RESULT \
  NXBOOTSTRAP_TEST_EXIT=$expected_status \
  NXBOOTSTRAP_TEST_PM_HELPER=$TEST_ROOT/helper.txt \
  NXBOOTSTRAP_TEST_PM_FINISH=$TEST_ROOT/finish.txt \
  NXBOOTSTRAP_TEST_FOREIGN_EXIT=$TEST_ROOT/foreign-exit.txt \
  NXBOOTSTRAP_TEST_ORDER=$TEST_ROOT/order.txt \
  NXBOOTSTRAP_TEST_CONTROL_LD=$TEST_ROOT/control-ld.txt \
  NXBOOTSTRAP_PORTMASTER_ROOTS=$PM_DIR \
  NXBOOTSTRAP_LOCK_ROOT=$TEST_ROOT/locks \
  NXBOOTSTRAP_TEST_NO_TTY=1 \
  NXPORT_ID=synthetic \
  NXPORT_TITLE=Synthetic \
  NXPORT_SCHEMA_VERSION=2 \
  NXPORT_GAME_DIR=$GAME_DIR \
  NXPORT_ARCH=x86_64 \
  NXPORT_EXECUTABLE=fake-loader \
  NXPORT_ARGUMENT_MODE=game-dir-and-passthrough \
  NXPORT_HOME_MODE=port \
  NXPORT_NXEXTRACT=yes \
  NXPORT_NXEXTRACT_VERSION=1.2.7 \
  NXPORT_REQUIRED_FILES=$'payload.bin\nfake-loader' \
  NXPORT_PRIVATE_LIBRARY_PATHS=libs \
  NXPORT_PREPARE_SCRIPT=prepare.sh \
  NXPORT_REQUIRED_CAPABILITIES=$'host.portmaster\ngraphics.gles2' \
  NXPORT_ENABLED_QUIRKS=adapter.synthetic \
  NXPORT_RUNTIME_REPORT=log-and-logo \
  LD_LIBRARY_PATH=$GAME_DIR/libs:$TEST_ROOT/firmware-libs \
    bash -c 'source "$1"; shift; nxbootstrap_main "$@"' _ \
      "$PROJECT_ROOT/nxbootstrap.sh" "$@"
  local status=$?
  set -e
  [[ $status -eq $expected_status ]] ||
    fail "launcher returned $status, expected $expected_status"
}

