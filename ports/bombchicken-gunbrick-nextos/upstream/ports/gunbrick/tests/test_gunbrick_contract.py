#!/usr/bin/env python3
"""Hermetic release-contract gate for Gunbrick Reloaded.

The gate audits source, generated launcher, BYO recipe, release manifest and
the project-built Linux ELF. It never executes owner Android code.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import tempfile


PORT = Path(__file__).resolve().parents[1]
REPO = PORT.parents[1]
PUBLIC_ELF = PORT / "build" / "gunbrick-nextos"


def require(value: bool, message: str) -> None:
    if not value:
        raise AssertionError(message)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def no_duplicates(pairs):
    result = {}
    for key, value in pairs:
        require(key not in result, f"duplicate JSON key: {key}")
        result[key] = value
    return result


def load_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"),
                      object_pairs_hook=no_duplicates)


def run(*argv: str, cwd: Path | None = None) -> str:
    result = subprocess.run(argv, cwd=cwd, text=True,
                            stdout=subprocess.PIPE,
                            stderr=subprocess.PIPE, check=False)
    require(result.returncode == 0,
            f"{' '.join(argv)} failed ({result.returncode})\n"
            f"{result.stdout}\n{result.stderr}")
    return result.stdout


def check_launcher_and_contract() -> None:
    nxport = load_json(PORT / "nxport.json")
    require(nxport["schema_version"] == 2, "nxport schema drift")
    require(nxport["id"] == "gunbrick", "wrong port id")
    require(nxport["executable"] == "gunbrick-nextos",
            "noncanonical public executable")
    require(nxport["nxextract"] == {"mode": "yes", "version": "1.2.6"},
            "NXExtract contract drift")
    require(len(nxport["required_capabilities"]) ==
            len(set(nxport["required_capabilities"])),
            "duplicate capability")
    for capability in (
        "host.portmaster", "host.aarch64-libs", "graphics.window",
        "graphics.gles2", "graphics.egl", "graphics.egl-config",
        "graphics.drawable", "input.controller-mapping",
        "input.controller-api",
    ):
        require(capability in nxport["required_capabilities"],
                f"missing capability: {capability}")

    launcher = (PORT / "Gunbrick.sh").read_text(encoding="utf-8")
    require("generated by nxbootstrap 0.6.3" in launcher,
            "launcher is not nxbootstrap 0.6.3")
    for guarantee in ("flock -n 9", 'wait "$game_pid"',
                      "nxbootstrap_finish", "pm_finish"):
        require(guarantee in launcher,
                f"launcher guarantee missing: {guarantee}")
    for retired in ("nxbootstrap.sh", "nxbootstrap-0.5.1.sh",
                    "nxdeployment.json", "run.sh"):
        require(not (PORT / retired).exists(),
                f"retired launcher artifact remains: {retired}")

    # The launcher generator is part of the internal NextOS framework and is
    # not distributed; regeneration is only checked on internal machines.
    generator = REPO / "framework/nxbootstrap/tools/generate-port.py"
    if generator.exists():
        with tempfile.TemporaryDirectory(prefix="gunbrick-launcher-") as temp:
            run(sys.executable, str(generator), str(PORT / "nxport.json"),
                "--output", temp)
            generated = Path(temp) / "Gunbrick.sh"
            require(generated.read_bytes() ==
                    (PORT / "Gunbrick.sh").read_bytes(),
                    "checked-in launcher is stale")


